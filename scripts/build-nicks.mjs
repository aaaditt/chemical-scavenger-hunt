// Emits src/lib/nicks.ts: element symbol -> nickname ONLY. Never import content/catalog.json from client
// code; it holds recipes and locked hints.
import { readFileSync, writeFileSync } from "node:fs";
const cat = JSON.parse(readFileSync(new URL("../content/catalog.json", import.meta.url), "utf8"));
const map = Object.fromEntries(cat.elements.filter((e) => e.nick).map((e) => [e.symbol, e.nick]));
const out = `// Generated by scripts/build-nicks.mjs from content/catalog.json. Do not edit.\nexport const NICK: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`;
writeFileSync(new URL("../src/lib/nicks.ts", import.meta.url), out);
console.log(`nicks: ${Object.keys(map).length}`);
