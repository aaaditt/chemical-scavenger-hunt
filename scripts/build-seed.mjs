// Generates SQL from content/catalog.json.
//   supabase/catalog.sql : idempotent upsert of catalysts, elements, compounds (safe to run on production)
//   supabase/seed.sql    : local-dev only QR codes (DEV-prefixed) so you can play without printing anything
// Usage: node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(readFileSync(resolve(root, "content/catalog.json"), "utf8"));

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

let sql = `-- GENERATED by scripts/build-seed.mjs from content/catalog.json. Do not edit by hand.\n\n`;

sql += `insert into public.catalysts (id, name, emoji, flavor) values\n`;
sql += catalog.catalysts.map((c) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.emoji)}, ${q(c.flavor)})`).join(",\n");
sql += `\non conflict (id) do update set name = excluded.name, emoji = excluded.emoji, flavor = excluded.flavor;\n\n`;

sql += `insert into public.elements (symbol, name, tier, points, giftable) values\n`;
sql += catalog.elements
  .map((e) => `  (${q(e.symbol)}, ${q(e.name)}, ${q(e.tier)}, ${catalog.tiers[e.tier].elementPoints}, ${e.giftable})`)
  .join(",\n");
sql += `\non conflict (symbol) do update set name = excluded.name, tier = excluded.tier, points = excluded.points, giftable = excluded.giftable;\n\n`;

sql += `insert into public.compounds (id, name, formula, recipe, catalyst, tier, points, riddle, locked_hint) values\n`;
sql += catalog.compounds
  .map(
    (c) =>
      `  (${q(c.id)}, ${q(c.name)}, ${q(c.formula)}, ${j(c.recipe)}, ${q(c.catalyst)}, ${q(c.tier)}, ${c.points}, ${q(c.riddle)}, ${q(c.lockedHint)})`
  )
  .join(",\n");
sql += `\non conflict (id) do update set name = excluded.name, formula = excluded.formula, recipe = excluded.recipe,
  catalyst = excluded.catalyst, tier = excluded.tier, points = excluded.points, riddle = excluded.riddle,
  locked_hint = excluded.locked_hint;\n`;

writeFileSync(resolve(root, "supabase/catalog.sql"), sql);

// Dev seed: one QR per element (DEV-H, DEV-NA, ...), capped for rare, dormant for isotopes, plus a few hint QRs.
const capFor = { common: "null", uncommon: "null", rare: "5", isotope: "3" };
let dev = `-- GENERATED by scripts/build-seed.mjs. LOCAL DEV ONLY.\n\n`;
dev += `insert into public.qr_codes (code, kind, element, cap, location_label, active_from) values\n`;
dev += catalog.elements
  .map(
    (e) =>
      `  ('DEV-${e.symbol.toUpperCase()}', 'element', ${q(e.symbol)}, ${capFor[e.tier]}, 'Dev desk', ${
        e.tier === "isotope" ? "'infinity'" : "null"
      })`
  )
  .join(",\n");
dev += `\non conflict (code) do nothing;\n\n`;
const hinted = catalog.compounds.filter((c) => c.lockedHint).slice(0, 5);
dev += `insert into public.qr_codes (code, kind, compound, location_label) values\n`;
dev += hinted.map((c) => `  ('DEV-HINT-${c.id.toUpperCase()}', 'hint', ${q(c.id)}, 'Dev desk')`).join(",\n");
dev += `\non conflict (code) do nothing;\n`;
writeFileSync(resolve(root, "supabase/seed.sql"), dev);

console.log(`OK: catalog.sql (${catalog.compounds.length} compounds) + seed.sql (${catalog.elements.length + hinted.length} dev QRs)`);
